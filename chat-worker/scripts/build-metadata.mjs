import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));

function git(...args) {
  return execFileSync("git", ["-c", `safe.directory=${root}`, "-C", root, ...args], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
}

let commit = null;
let dirty = null;
const explicitDirty = process.env.ORGPORTAL_BUILD_DIRTY?.toLowerCase();
try {
  if (realpathSync(git("rev-parse", "--show-toplevel")) !== realpathSync(root)) throw new Error("Not an OrgPortal Git checkout");
  const sha = git("rev-parse", "HEAD");
  if (!/^[a-f0-9]{40,64}$/.test(sha)) throw new Error("Invalid commit");
  commit = sha;
  dirty = Boolean(git("status", "--porcelain", "--untracked-files=normal"));
} catch {
  const explicit = process.env.ORGPORTAL_BUILD_COMMIT;
  if (explicit && !/^[a-f0-9]{40,64}$/i.test(explicit)) throw new Error("ORGPORTAL_BUILD_COMMIT must be a full Git SHA");
  commit = explicit ? explicit.toLowerCase() : null;
  dirty = explicitDirty === "true" ? true : explicitDirty === "false" ? false : null;
}

const output = new URL("../src/generated/buildMetadata.ts", import.meta.url);
let previous = null;
try {
  const match = readFileSync(output, "utf8").match(/export const buildMetadata = (\{.*\}) as const;/);
  if (match) previous = JSON.parse(match[1]);
} catch {
  // The first build creates the generated file.
}
const metadata = {
  commit,
  dirty,
  builtAt: previous?.commit === commit && previous?.dirty === dirty
    ? previous.builtAt
    : new Date().toISOString(),
};
const content = `// Generated by scripts/build-metadata.mjs. Do not commit.\nexport const buildMetadata = ${JSON.stringify(metadata)} as const;\n`;
mkdirSync(new URL("../src/generated/", import.meta.url), { recursive: true });
if (content !== (previous ? readFileSync(output, "utf8") : "")) writeFileSync(output, content);
console.log(`Chat worker build commit: ${commit ?? "unknown"}${dirty ? " (working tree modified)" : ""}`);
