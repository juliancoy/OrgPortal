const test = require('node:test')
const assert = require('node:assert/strict')
const {execFileSync} = require('node:child_process')
const {existsSync,mkdtempSync,readFileSync,statSync,writeFileSync,mkdirSync,rmSync} = require('node:fs')
const {tmpdir} = require('node:os')
const path = require('node:path')
const arch=execFileSync('dpkg',['--print-architecture'],{encoding:'utf8'}).trim()
const artifact=path.join(__dirname,'dist',`orgportal_3.0.0_${arch}.deb`)
test('replacement Debian package has opt-in conflict, runnable launcher and sandbox', {skip:!existsSync(artifact)},()=>{
 const dir=mkdtempSync(path.join(tmpdir(),'orgportal-package-'))
 try {
  const metadata=execFileSync('dpkg-deb',['-f',artifact],{encoding:'utf8'})
  assert.match(metadata,/Package: orgportal\n/)
  assert.match(metadata,/Conflicts: lifetech\n/)
  assert.match(metadata,/Replaces: lifetech\n/)
  execFileSync('dpkg-deb',['-x',artifact,dir])
  for(const file of ['usr/bin/orgportal','usr/share/applications/orgportal.desktop','opt/orgportal/resources/app/main.cjs','opt/orgportal/resources/app/icon.png'])assert.ok(existsSync(path.join(dir,file)),file)
  const listing=execFileSync('dpkg-deb',['-c',artifact],{encoding:'utf8'})
  assert.match(listing,/-rwsr-xr-x root\/root\s+\d+ .*\.\/opt\/orgportal\/chrome-sandbox/)
  const app=JSON.parse(readFileSync(path.join(dir,'opt/orgportal/resources/app/package.json')))
  assert.equal(app.productName,'OrgPortal')
  assert.ok(readFileSync(path.join(dir,'opt/orgportal/resources/app/main.cjs'),'utf8').includes('https://lifetech.fyi/'))
  assert.ok(!existsSync(path.join(dir,'usr/bin/lifetech')))
  const launcher=readFileSync(path.join(dir,'usr/bin/orgportal'),'utf8').replaceAll('/opt/orgportal',path.join(dir,'opt/orgportal'))
  writeFileSync(path.join(dir,'launch'),launcher,{mode:0o755})
  writeFileSync(path.join(dir,'opt/orgportal/electron'),'#!/bin/sh\nprintf "%s\\n" "$@"\n',{mode:0o755})
  const args=execFileSync(path.join(dir,'launch'),['--dev','http://localhost:5173/a b'],{encoding:'utf8'}).trim().split('\n')
  assert.deepEqual(args,[path.join(dir,'opt/orgportal/resources/app/main.cjs'),'--dev','http://localhost:5173/a b'])
 } finally {rmSync(dir,{recursive:true,force:true})}
})
