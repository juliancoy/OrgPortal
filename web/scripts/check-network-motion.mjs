import assert from 'node:assert/strict'
import {chromium} from '@playwright/test'
const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_BINARY||'/usr/bin/google-chrome',args:['--no-sandbox']})
try{
 for(const mode of ['svg','webgl']){
  const page=await browser.newPage({viewport:{width:1440,height:900}})
  if(mode==='svg')await page.addInitScript(()=>{const old=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(k,...a){return k.includes('webgl')?null:old.call(this,k,...a)}})
  await page.route('**/api/org/api/network/**',r=>r.fulfill({status:503,body:'Saved evidence'}))
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto((process.env.MAP_ORIGIN||'http://127.0.0.1:5193')+'/ecosystem/network')
  await page.waitForFunction(()=>document.querySelector('#network-status')?.textContent.includes('visible links'))
  assert.equal(await page.locator('#zoom-sparse').isChecked(),false,`${mode} shows small nodes by default`)
  await page.locator('#network-labels button:not([hidden])').first().dispatchEvent('pointerenter')
  const preview=page.locator('#network-detail')
  await preview.locator('.eco-preview-totals').waitFor()
  assert.equal(await preview.locator('.eco-preview-totals dt').allTextContents().then(labels=>labels.join(',')),'Total received,Total disbursed')
  assert.equal(await preview.locator('a').last().getAttribute('href').then(href=>href.includes('/orgs/')),true)
  assert.equal(await preview.locator('.eco-relations').count(),0)
  const firstNode=page.locator('#network-labels button:not([hidden])').first()
  const pinnedName=await firstNode.textContent()
  await firstNode.dispatchEvent('click')
  const pinnedUrl=page.url()
  await page.reload()
  await page.waitForFunction(()=>document.querySelector('#network-status')?.textContent.includes('visible links'))
  await preview.getByRole('button',{name:'Close pinned organization'}).waitFor()
  assert.equal(page.url(),pinnedUrl,`${mode} restores pinned details from its URL`)
  const pinned=await preview.innerHTML()
  const otherNode=page.locator('#network-labels button').filter({hasNotText:pinnedName}).first()
  await otherNode.dispatchEvent('pointerenter')
  await otherNode.dispatchEvent('focus')
  if(mode==='svg')await page.locator('[data-edge-id]').first().dispatchEvent('pointerenter')
  assert.equal(await preview.innerHTML(),pinned,`${mode} pinned details survive hover and focus`)
  await preview.getByRole('button',{name:'Close pinned organization'}).click()
  assert.equal(new URL(page.url()).searchParams.has('org'),false)
  await otherNode.dispatchEvent('pointerenter')
  assert.notEqual(await preview.innerHTML(),pinned,`${mode} hover resumes after closing`)
  await preview.locator('.eco-preview-totals').waitFor()
  const positions=()=>page.locator('#network-labels button').evaluateAll(ns=>JSON.stringify(ns.map(n=>n.style.cssText)))
  const first=await positions();await page.waitForTimeout(300);assert.notEqual(await positions(),first,`${mode} should animate`)
  await page.locator('#live-physics').evaluate(el=>{el.checked=false;el.dispatchEvent(new Event('change'))})
  await page.waitForTimeout(100);const paused=await positions();await page.waitForTimeout(250);assert.equal(await positions(),paused,`${mode} should pause`)
  if(mode==='svg'){
   const before=await page.locator('[data-edge-id]').first().getAttribute('d')
   await page.locator('#live-physics').evaluate(el=>{el.checked=true;el.dispatchEvent(new Event('change'))})
   await page.waitForTimeout(200);assert.notEqual(await page.locator('[data-edge-id]').first().getAttribute('d'),before)
  }
  assert.deepEqual(errors,[]);console.log(mode,'motion, pause and geometry verified');await page.close()
 }
 const page=await browser.newPage({reducedMotion:'reduce',viewport:{width:1440,height:900}})
 await page.route('**/api/org/api/network/**',r=>r.fulfill({status:503,body:'Saved evidence'}))
 await page.goto((process.env.MAP_ORIGIN||'http://127.0.0.1:5193')+'/ecosystem/network')
 await page.waitForFunction(()=>document.querySelector('#network-status')?.textContent.includes('visible links'))
 assert.equal(await page.locator('#live-physics').isChecked(),false);console.log('reduced motion defaults to paused');await page.close()
}finally{await browser.close()}
